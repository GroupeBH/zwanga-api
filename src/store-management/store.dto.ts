export function storeRange(query: StoreRangeDto, maxDays = 93): StoreRange {
  const to = query.to ?? day();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(to) || !Number.isFinite(Date.parse(to)))
    throw new BadRequestException('Date de fin invalide.');
  const from =
    query.from ??
    day(new Date(new Date(`${to}T00:00:00Z`).getTime() - 29 * 86400000));
  const valid = (s: string) =>
    /^\d{4}-\d{2}-\d{2}$/.test(s) &&
    Number.isFinite(Date.parse(s)) &&
    day(new Date(s)) === s;
  if (
    !valid(from) ||
    !valid(to) ||
    from > to ||
    to > day() ||
    (Date.parse(to) - Date.parse(from)) / 86400000 >= maxDays
  )
    throw new BadRequestException(
      `Période invalide (maximum ${maxDays} jours, sans date future).`,
    );
  return { from, to };
}
